"""The results section of README.md, rebuilt from result files so no number in it is typed by hand.

Each set of runs (results/<machine>/<matrix>/) gets one table with a row per guard. The section sits between two
HTML comment markers, and only the text between them is replaced.
"""
import json
from pathlib import Path
from typing import Dict, List

from .tables import rates

START = "<!-- results:start (generated by `stalehand readme`; do not edit) -->"
END = "<!-- results:end -->"


def _pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def _sets(root) -> Dict[str, List[dict]]:
    """Rows of every results.jsonl under root, grouped by the machine/matrix directory above each job."""
    root = Path(root)
    out: Dict[str, List[dict]] = {}
    for path in sorted(root.rglob("results.jsonl")):
        key = "/".join(path.relative_to(root).parts[:-2]) or "."
        out.setdefault(key, []).extend(json.loads(ln) for ln in path.read_text().splitlines() if ln.strip())
    return dict(sorted(out.items()))


def _table(rows: List[dict]) -> List[str]:
    lines = ["| guard | episodes | successes | success rate | stale rate on relevant changes "
             "| false alarms on harmless changes | planner calls | model seconds |", "|" + "---|" * 8]
    for g in rates(rows, by=("guard",)):
        mine = [r for r in rows if r["guard"] == g["guard"]]
        relevant = [r for r in mine if r["change_kind"] == "relevant"]
        stale = sum(r["outcome"] == "stale" for r in relevant) / len(relevant) if relevant else None
        seconds = sum(r.get("model_seconds", 0) for r in mine) / len(mine)
        lines.append(f"| {g['guard']} | {g['n']} | {g['success']} | {_pct(g['success_rate'])} | {_pct(stale)} "
                     f"| {_pct(g['false_alarm_rate'])} | {g['planner_calls']:.1f} | {seconds:.1f} |")
    return lines


def section(root) -> str:
    sets = _sets(root)
    out = [f"Built from {sum(map(len, sets.values()))} scored episodes under `{Path(root).as_posix()}/`. "
           "Rates are per episode; planner calls and model seconds are means per episode. Paired comparisons with "
           "confidence intervals are in the full report (`stalehand report`)."]
    for name, rows in sets.items():
        executors = sorted({r.get("run", {}).get("executor", "?") for r in rows})
        out += ["", f"### `{name}`", "", f"Executor: {', '.join(executors)}.", ""] + _table(rows)
    return "\n".join(out) + "\n"


def splice(doc: str, body: str) -> str:
    """doc with the text between START and END replaced by body."""
    i, j = doc.find(START), doc.find(END)
    if i < 0 or j < i:
        raise ValueError("README has no results markers")
    return doc[:i + len(START)] + "\n" + body + doc[j:]
